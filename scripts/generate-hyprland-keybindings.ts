#!/usr/bin/env bun

import { resolve } from "node:path";

const repositoryRoot = resolve(import.meta.dir, "..");
const configDirectory = resolve(repositoryRoot, "nix/modules/hyprland");
const commonConfigPath = resolve(configDirectory, "config.lua");
const checkOnly = Bun.argv.slice(2).includes("--check");

const outputPath = resolve(configDirectory, "README.md");
const shellConfigPath = resolve(configDirectory, "noctalia.lua");

type Keybinding = {
  action: string;
  section: string;
  shortcut: string;
};

const keyLabels = new Map<string, string>([
  ["SUPER", "Super"],
  ["CTRL", "Ctrl"],
  ["SHIFT", "Shift"],
  ["ALT", "Alt"],
  ["mouse:272", "Left Click"],
  ["mouse:273", "Right Click"],
  ["mouse_down", "Wheel Down"],
  ["mouse_up", "Wheel Up"],
  ["mouse_left", "Wheel Left"],
  ["mouse_right", "Wheel Right"],
]);

function escapeMarkdown(value: string): string {
  return value.replaceAll("|", "\\|");
}

function formatShortcut(shortcut: string): string {
  return shortcut
    .split("+")
    .map((key) => key.trim())
    .map((key) => keyLabels.get(key) ?? key)
    .join(" + ");
}

function renderTable(keybindings: Keybinding[]): string {
  const rows = [
    ["Shortcut", "Action"],
    ...keybindings.map((keybinding) => [
      formatShortcut(keybinding.shortcut),
      escapeMarkdown(keybinding.action),
    ]),
  ];
  const columnWidths = rows[0].map((_, columnIndex) =>
    Math.max(...rows.map((row) => row[columnIndex].length)),
  );
  const renderRow = (row: string[]) =>
    `| ${row.map((cell, index) => cell.padEnd(columnWidths[index])).join(" | ")} |`;

  return [
    renderRow(rows[0]),
    renderRow(columnWidths.map((width) => "-".repeat(width))),
    ...rows.slice(1).map(renderRow),
  ].join("\n");
}

// A comment directly above a bind names the section for the binds that follow.
function readKeybindings(config: string, configPath: string): Keybinding[] {
  const keybindings: Keybinding[] = [];
  const lines = config.split("\n");
  let section = "Other";

  for (const [lineIndex, line] of lines.entries()) {
    const trimmedLine = line.trim();

    if (!trimmedLine.startsWith("hl.bind(")) {
      continue;
    }

    const sectionMatch = lines[lineIndex - 1]?.match(/^--\s+(.+?)\s*$/);
    section = sectionMatch?.[1] ?? section;

    const shortcut = trimmedLine.match(/^hl\.bind\("([^"]+)"/)?.[1];
    const action = trimmedLine.match(/description = "([^"]+)"/)?.[1];

    if (!shortcut || !action) {
      throw new Error(
        `Expected hl.bind("<keys>", ..., { description = "..." }) on line ${lineIndex + 1} of ${configPath}`,
      );
    }

    // Lid and other switch events are not keyboard shortcuts.
    if (shortcut.startsWith("switch:")) {
      continue;
    }

    keybindings.push({ action, section, shortcut });
  }

  if (keybindings.length === 0) {
    throw new Error(`Could not find any hl.bind() calls in ${configPath}`);
  }

  return keybindings;
}

function renderReference(keybindings: Keybinding[]): string {
  const sections = Map.groupBy(keybindings, (keybinding) => keybinding.section);
  const renderedSections = [...sections].map(
    ([section, sectionKeybindings]) =>
      `## ${section}\n\n${renderTable(sectionKeybindings)}`,
  );

  return `<!-- This file is generated by scripts/generate-hyprland-keybindings.ts. Do not edit it directly. -->

# Hyprland keyboard reference

${renderedSections.join("\n\n")}`;
}

const commonKeybindings = readKeybindings(
  await Bun.file(commonConfigPath).text(),
  commonConfigPath,
);

const shellKeybindings = readKeybindings(
  await Bun.file(shellConfigPath).text(),
  shellConfigPath,
);
const reference = `${renderReference([
  ...commonKeybindings,
  ...shellKeybindings,
])}\n`;

if (checkOnly) {
  const existingReference = await Bun.file(outputPath)
    .text()
    .catch(() => undefined);

  if (reference !== existingReference) {
    console.error(
      `${outputPath} is stale. Run bun scripts/generate-hyprland-keybindings.ts.`,
    );
    process.exitCode = 1;
  }
} else {
  await Bun.write(outputPath, reference);
}
